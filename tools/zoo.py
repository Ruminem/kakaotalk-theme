# -*- coding: utf-8 -*-
"""네온관으로 그리는 동물 열의 선 데이터.

배경(scenes.neonbg)과 기본 프로필(charbubble) 양쪽에서 같은 동물을 그린다. 그래서 그림을 그리는
코드는 여기 두지 않고 좌표만 낸다 — scenes 와 charbubble 이 서로를 부르지 않게 하려는 것이다.

왜 네온관인가. 말풍선과 같은 재질이라 계열 안에서 따로 놀지 않는다. 색을 칠한 캐릭터를 얹으면
어두운 배경 위에 스티커를 붙인 것으로 보였다. neonwall 이 이미 하트·별·초승달을 이 방식으로
배치해 잘 나오고 있어서, 동물은 그걸 더 크고 낫게 만든 것이다.

**카카오 프렌즈와 겹치는 동물은 쓰지 않는다** — 사자·복숭아·토끼·개·고양이·오리·두더지·악어.
우리가 새로 그려도 카톡 안에서는 공식 캐릭터를 흉내 낸 것으로 읽힌다. 여우는 개와 갈리게
귀를 크게 세우고 주둥이를 길고 뾰족하게 뺐다.

폰 크기에서 읽히게 하려고 지키는 것 셋.

1. **획을 끊지 않는다.** 이어지는 선이라야 관으로 보인다. 토막 난 선은 빛나는 부스러기가 된다
2. **잔 무늬를 넣지 않는다.** 흐림이 얹히면 잔선은 뭉개져 덩어리가 된다
3. **눈만 채운다.** 나머지는 선이고 눈은 채운 점이다. 눈만 채워도 얼굴로 읽힌다

**무엇인지 알려주는 신호는 몸통 한가운데가 아니라 끝에 있다** — 사슴은 뿔, 해마는 대롱 주둥이와
감긴 꼬리, 여우는 선 귀다. 그래서 몸이 반만 보이면 무슨 동물인지 알 수 없다. 배경에 놓을 때
말풍선을 피해야 하는 이유가 이것이다(scenes.NEON_SPOTS).

좌표는 -1~1 단위계다. y 는 아래가 양수. 각 함수는 (선 목록, 채울 점 목록) 을 낸다.
점은 (x, y, r) 이고 눈에만 쓴다.
"""
import math

TAU = math.pi * 2


def _arc(cx, cy, rx, ry, a0, a1, n=40):
    return [(cx + math.cos(math.radians(a)) * rx, cy + math.sin(math.radians(a)) * ry)
            for a in [a0 + (a1 - a0) * i / n for i in range(n + 1)]]


def _ring(cx, cy, rx, ry=None, n=44):
    return _arc(cx, cy, rx, ry if ry is not None else rx, 0, 360, n)


def _wavy(x0, x1, y, amp, waves, n=48):
    """아래 가장자리의 물결. 해파리 갓에 쓴다."""
    return [(x0 + (x1 - x0) * i / n, y + math.sin(i / n * TAU * waves) * amp)
            for i in range(n + 1)]


def _curl(x, y, dx, dy, turns, n=40):
    """내려가며 좌우로 흔들리고 끝으로 갈수록 폭이 주는 다리."""
    return [(x + math.sin(i / n * TAU * turns) * dx * (1 - i / n * .45), y + dy * i / n)
            for i in range(n + 1)]


# --- 바다 ----------------------------------------------------------------

def jelly():
    """해파리. 갓은 위가 둥글고 아래가 물결이며 다리 넷이 곧게 늘어진다."""
    dome = _arc(0, -.15, .62, .55, 180, 360) + _wavy(.62, -.62, -.15, .09, 2.5)
    return [dome] + [_curl(x, -.08, .12, 1.0, 1.6) for x in (-.40, -.14, .14, .40)], \
           [(-.24, -.26, .10), (.24, -.26, .10)]


def whale():
    """고래. 한 붓 몸통에 갈라진 꼬리, 위로 물을 뿜는다."""
    body = (_arc(0, 0, .78, .46, 160, 340) + [(.62, -.18), (.86, -.46), (.80, 0), (.86, .46), (.62, .18)]
            + _arc(0, 0, .78, .46, 20, 200))
    fin = _arc(.02, .18, .26, .20, 20, 160)
    spout = [[(-.42, -.50), (-.52, -.92)], [(-.30, -.52), (-.24, -.94)], [(-.38, -.52), (-.38, -.98)]]
    return [body, fin] + spout, [(-.44, -.08, .09)]


def octopus():
    """문어. 해파리와 갈리는 것이 관건이다 — 해파리는 다리가 아래로 곧게 늘어지고 갓이 물결지는데,
    문어는 머리가 통통한 주머니고 다리가 옆으로 벌어졌다가 끝이 안으로 감긴다."""
    head = _arc(0, -.30, .46, .44, 175, 365)
    skirt = [(-.46, -.28), (-.40, -.02), (-.20, .08), (0, .04), (.20, .08), (.40, -.02), (.46, -.28)]
    legs = []
    for i, ang in enumerate((-72, -38, 0, 38, 72)):
        a = math.radians(ang)
        legs.append([(math.sin(a) * (.30 + t * .62) + math.sin(t * 7 + i) * .12 * t,
                      .04 + t * .82 - t * t * .22)
                     for t in [k / 25.0 for k in range(26)]])
    return [head, skirt] + legs, [(-.18, -.34, .11), (.18, -.34, .11)]


def seahorse():
    """해마. 옆에서 본 모습이라 읽히는 것은 셋뿐이다 — 앞으로 뻗은 대롱 주둥이, 배가 불룩한 S 자 몸,
    한 바퀴 넘게 감긴 꼬리. 처음엔 통짜 윤곽으로 그렸는데 덩어리로 보여 무엇인지 몰랐다."""
    back = [(-.62, -.52), (-.34, -.62), (-.20, -.78), (-.04, -.66), (.06, -.80), (.18, -.62),
            (.26, -.40), (.24, -.16), (.14, .08), (.10, .30)]
    tail = [(.02 + math.cos(math.radians(-70 + t * 430)) * (.30 * (1 - t * .72)),
             .50 + math.sin(math.radians(-70 + t * 430)) * (.30 * (1 - t * .72)))
            for t in [k / 33.0 for k in range(34)]]
    belly = [(-.62, -.40), (-.36, -.44), (-.22, -.30), (-.14, -.06), (-.16, .18), (-.06, .40), (.02, .50)]
    return [back + tail[:1], tail, belly, [(-.62, -.52), (-.62, -.40)],
            [(.22, -.22), (.40, -.10), (.22, .02)]], [(-.26, -.50, .075)]


